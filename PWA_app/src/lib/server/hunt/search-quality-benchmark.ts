export interface BenchmarkCandidate {
  id: string;
  title: string;
  description: string;
  /** Human-labelled graded relevance; never generated by the engine. */
  relevance: RelevanceGrade;
  expectedTerms?: string[];
  /**
   * Optional human-authored structured price in toman for evaluation-only
   * provider/price-bound coverage. Null/absent = unknown price (stays per
   * contract). Never inferred by parsing descriptions.
   */
  price?: number | null;
  note: string;
}

