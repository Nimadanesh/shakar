export interface RankingMetrics {
  precisionAtK: number;
  recallAtK: number | null;
  ndcgAtK: number;
  returned: number;
  relevantReturned: number;
  relevantInPool: number;
}

/** Metrics for an ordered list of candidate IDs against reviewed labels. */
export function evaluateRanking(
  rankedIds: readonly string[],
  labels: Readonly<Record<string, number>>,
  k = 5
): RankingMetrics {
  const safeK = Math.max(1, Math.floor(k));
  const top = rankedIds.slice(0, safeK);
  const relevantReturned = top.filter((id) => (labels[id] ?? 0) >= 2).length;
  const relevantInPool = Object.values(labels).filter((grade) => grade >= 2).length;
  const dcg = top.reduce((sum, id, i) => sum + ((2 ** (labels[id] ?? 0) - 1) / Math.log2(i + 2)), 0);
  const idealGrades = Object.values(labels).sort((a, b) => b - a).slice(0, safeK);
  const idcg = idealGrades.reduce((sum, grade, i) => sum + ((2 ** grade - 1) / Math.log2(i + 2)), 0);
  return {
    precisionAtK: relevantReturned / safeK,
    recallAtK: relevantInPool === 0 ? null : relevantReturned / relevantInPool,
    ndcgAtK: idcg === 0 ? 0 : dcg / idcg,
    returned: top.length,
    relevantReturned,
    relevantInPool,
  };
}
